create or replace function public.voucher_reserve(
    p_hotel_id text,
    p_ru integer,
    p_en integer
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, wifi_voucher
as $$
declare
    v_total integer := coalesce(p_ru, 0) + coalesce(p_en, 0);
    v_batch uuid := gen_random_uuid();
    v_ids bigint[];
    v_passwords jsonb;
begin
    perform wifi_voucher.require_role(p_hotel_id, array['admin', 'operator']);
    if coalesce(p_ru, 0) < 0 or coalesce(p_en, 0) < 0 or v_total < 1 or v_total > 500 then
        raise exception using errcode = '22023', message = 'Укажите от 1 до 500 карточек.';
    end if;
    perform wifi_voucher.release_stale(p_hotel_id);

    select array_agg(q.id order by q.id) into v_ids
    from (
        select p.id
        from wifi_voucher.passwords p
        where p.hotel_id = p_hotel_id and p.status = 'available'
        order by p.id
        for update skip locked
        limit v_total
    ) q;

    if coalesce(cardinality(v_ids), 0) <> v_total then
        raise exception using errcode = 'P0001',
            message = format('Недостаточно доступных паролей: нужно %s.', v_total);
    end if;

    update wifi_voucher.passwords p
    set status = 'reserved', batch_id = v_batch, reserved_at = now()
    where p.id = any(v_ids);

    insert into wifi_voucher.generations(id, hotel_id, ru_count, en_count, total_count, status)
    values (v_batch, p_hotel_id, p_ru, p_en, v_total, 'reserved');

    select jsonb_agg(p.password order by p.id) into v_passwords
    from wifi_voucher.passwords p where p.id = any(v_ids);

    insert into wifi_voucher.audit_events(hotel_id, user_id, action, entity_type, entity_id, details)
    values (p_hotel_id, auth.uid(), 'generation.reserve', 'generation', v_batch::text,
            jsonb_build_object('ru', p_ru, 'en', p_en, 'total', v_total));

    return jsonb_build_object(
        'batch_id', v_batch,
        'passwords', v_passwords,
        'ru_count', p_ru,
        'en_count', p_en,
        'stats', wifi_voucher.stats_json(p_hotel_id)
    );
end;
$$;

create or replace function public.voucher_generation_commit(
    p_hotel_id text,
    p_batch_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, wifi_voucher
as $$
declare
    v_count integer;
begin
    perform wifi_voucher.require_role(p_hotel_id, array['admin', 'operator']);
    perform 1 from wifi_voucher.generations g
    where g.id = p_batch_id and g.hotel_id = p_hotel_id and g.status = 'reserved'
    for update;
    if not found then
        raise exception using errcode = 'P0002', message = 'Резерв генерации не найден.';
    end if;

    update wifi_voucher.passwords p
    set status = 'used', used_at = now(), reserved_at = null
    where p.hotel_id = p_hotel_id and p.batch_id = p_batch_id and p.status = 'reserved';
    get diagnostics v_count = row_count;
    update wifi_voucher.generations g
    set status = 'completed', completed_at = now(), error = null
    where g.id = p_batch_id;
    insert into wifi_voucher.audit_events(hotel_id, user_id, action, entity_type, entity_id, details)
    values (p_hotel_id, auth.uid(), 'generation.commit', 'generation', p_batch_id::text,
            jsonb_build_object('count', v_count));
    return jsonb_build_object('committed', v_count, 'stats', wifi_voucher.stats_json(p_hotel_id));
end;
$$;

create or replace function public.voucher_generation_release(
    p_hotel_id text,
    p_batch_id uuid,
    p_error text default null
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, wifi_voucher
as $$
declare
    v_count integer;
begin
    perform wifi_voucher.require_role(p_hotel_id, array['admin', 'operator']);
